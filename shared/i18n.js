  /* ---------- Çeviri ---------- */
  const has = (o, k) => Object.prototype.hasOwnProperty.call(o, k);

  /** Metni etkin dile çevirir; {ad} yer tutucularını vars ile doldurur */
  function t(s, vars) {
    let out = s;
    if (lang === 'en' && has(EN, s)) out = EN[s];
    if (typeof out === 'function') return out(vars || {});
    return vars ? fill(out, vars) : out;
  }
  /** Uzun veya biçimli metinler için iki dilli seçim */
  const L = (tr, en) => (lang === 'en' ? en : tr);

  // Sözlükte olmayan metinlerde baştaki simge/emoji ayrılıp kalan kısım aranır ("📂 Dosya aç" → "📂 Open a file")
  const PREFIX = /^([^\p{L}\p{N}"“‘(<[*#`=~+−-]+\s)(.+)$/su;
  function lookup(core) {
    if (has(EN, core) && typeof EN[core] === 'string') return EN[core];
    const p = PREFIX.exec(core);
    if (p && has(EN, p[2]) && typeof EN[p[2]] === 'string') return p[1] + EN[p[2]];
    return null;
  }
  function trText(s) {
    if (!s || !/\p{L}/u.test(s)) return null;
    const m = /^(\s*)([\s\S]*?)(\s*)$/.exec(s);
    const r = lookup(m[2]);
    return r === null || r === m[2] ? null : m[1] + r + m[3];
  }

  /* ---------- Sayfadaki arayüzün otomatik çevirisi ---------- */
  const ATTRS = ['title', 'placeholder', 'aria-label'];
  const SKIP = '[translate="no"], [contenteditable="true"], [contenteditable=""], script, style';
  // Metin alanlarının içeriği kullanıcıya aittir; yalnızca öznitelikleri (placeholder vb.) çevrilir
  const userText = (n) => n.parentElement && n.parentElement.tagName === 'TEXTAREA';
  const skipped = (el) => !!(el && el.closest && el.closest(SKIP));

  function translateEl(el) {
    for (const a of ATTRS) {
      const v = el.getAttribute(a);
      if (v) { const r = trText(v); if (r !== null) el.setAttribute(a, r); }
    }
    if (el.dataset && el.dataset.en !== undefined && el.textContent !== el.dataset.en) el.textContent = el.dataset.en;
  }
  function apply(root) {
    if (lang !== 'en' || !root) return;
    if (root.nodeType === 3) {
      if (!skipped(root.parentElement) && !userText(root)) { const r = trText(root.data); if (r !== null) root.data = r; }
      return;
    }
    if (root.nodeType !== 1 || skipped(root)) return;
    translateEl(root);
    const w = document.createTreeWalker(root, NodeFilter.SHOW_ELEMENT | NodeFilter.SHOW_TEXT, {
      acceptNode: (n) => (n.nodeType === 1 && n.matches(SKIP) ? NodeFilter.FILTER_REJECT : NodeFilter.FILTER_ACCEPT),
    });
    let n;
    while ((n = w.nextNode())) {
      if (n.nodeType === 1) translateEl(n);
      else if (!userText(n)) { const r = trText(n.data); if (r !== null) n.data = r; }
    }
  }

  if (lang === 'en') {
    document.documentElement.lang = 'en';
    new MutationObserver((records) => {
      for (const rec of records) {
        if (rec.type === 'attributes') {
          if (!skipped(rec.target)) { const v = rec.target.getAttribute(rec.attributeName); const r = v && trText(v); if (r) rec.target.setAttribute(rec.attributeName, r); }
        } else rec.addedNodes.forEach(apply);
      }
    }).observe(document.documentElement, { childList: true, subtree: true, attributes: true, attributeFilter: ATTRS });
    const titleFix = () => { const r = trText(document.title); if (r) document.title = r; };
    document.addEventListener('DOMContentLoaded', () => { apply(document.documentElement); titleFix(); });
  }

  function setLang(l) {
    if (!LANGS.includes(l)) return;
    try { localStorage.setItem(KEY, l); } catch (e) { /* özel pencere */ }
  }

